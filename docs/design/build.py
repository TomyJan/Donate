"""Build the frozen design references without a frontend toolchain."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parent
PAGES = {"home": "index.html", "admin": "admin.html"}
# Static files use a valid branch link. serve.py injects the checkout's actual Git metadata.
BUILD_MARKER = "/* DESIGN_BUILD_METADATA */"
DEFAULT_BUILD = {"version": "0.0.1", "tag": "v0.0.1", "commit": "master", "onTag": False}


def compose(page):
    read = lambda name: (ROOT / "src" / name).read_text(encoding="utf-8")
    shared_script = read("shared/shell.js").replace("/* FROZEN_LOGO */", read("shared/logo.js").strip())
    title = "Donate — " + ("收据册" if page == "home" else "站点管理")
    return (
        "<!doctype html>\n<!-- Generated by docs/design/build.py; edit docs/design/src. -->\n"
        '<html lang="zh-CN">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width,initial-scale=1">\n'
        f"<title>{title}</title>\n"
        f'<style>\n{read("shared/preview.css")}\n{read("shared/shell.css")}\n{read(f"pages/{page}.css")}</style>\n'
        '<script src="../vendor/lucide.js"></script>\n'
        f"<script>globalThis.DonateDesignBuild={BUILD_MARKER}{json.dumps(DEFAULT_BUILD)};</script>\n"
        f"<script>\n{shared_script}</script>\n</head>\n<body>\n"
        f'{read(f"pages/{page}.html")}\n<script>\n{read(f"pages/{page}.js")}</script>\n'
        "</body>\n</html>\n"
    )


def check():
    stale = [name for page, name in PAGES.items()
             if not (ROOT / "preview" / name).exists()
             or (ROOT / "preview" / name).read_text(encoding="utf-8") != compose(page)]
    if stale:
        raise SystemExit("Regenerate design references: " + ", ".join(stale))
    print("Both design references match their shared sources.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        check()
    else:
        (ROOT / "preview").mkdir(exist_ok=True)
        for page, name in PAGES.items():
            (ROOT / "preview" / name).write_text(compose(page), encoding="utf-8")
            print("Built " + name)
